// Copies the Tabler icons and Montserrat font the UI uses into src/, so the packaged app needs no node_modules.
// Run: node scripts/build-assets.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const ICONS = ['trash', 'trash-x', 'search', 'refresh', 'sun', 'moon', 'folder', 'folder-open', 'world-search', 'package', 'apps',
  'brand-windows', 'bolt', 'alert-triangle', 'check', 'x', 'file', 'link', 'arrows-sort', 'arrow-up', 'arrow-down', 'shield-lock',
  'shield-check', 'eraser', 'info-circle', 'file-export', 'external-link', 'recycle', 'flower', 'loader-2', 'hierarchy-2', 'key',
  'circle-check', 'circle-x', 'player-play', 'dots-vertical', 'square-minus', 'copy', 'world', 'history', 'calendar', 'ruler',
  'versions', 'building', 'spray', 'database-export', 'archive', 'clock', 'ghost', 'player-stop', 'keyboard', 'brand-github'];
const dir = path.join(root, 'node_modules/@tabler/icons/icons/outline');
const out = {};
for (const n of ICONS) {
  const svg = fs.readFileSync(path.join(dir, n + '.svg'), 'utf8');
  out[n] = svg.replace(/<svg[\s\S]*?>/, '').replace(/<\/svg>/, '').replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none" \/>/, '').replace(/\s+/g, ' ').trim();
}
fs.writeFileSync(path.join(root, 'src/icons.js'),
  '// Generated by scripts/build-assets.js from Tabler Icons (MIT, tabler.io/icons). Do not edit by hand.\nwindow.TABLER = ' + JSON.stringify(out, null, 0) + ';\n');
for (const w of [400, 500, 600, 700]) {
  fs.copyFileSync(path.join(root, `node_modules/@fontsource/montserrat/files/montserrat-latin-${w}-normal.woff2`), path.join(root, `src/fonts/montserrat-${w}.woff2`));
  fs.copyFileSync(path.join(root, `node_modules/@fontsource/montserrat/files/montserrat-latin-ext-${w}-normal.woff2`), path.join(root, `src/fonts/montserrat-ext-${w}.woff2`));
}
console.log('icons:', ICONS.length, 'fonts: 8');
